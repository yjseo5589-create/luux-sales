import assert from 'node:assert/strict';
import {projectStage,projectResult,projectCompanyIds,filterProjects} from '../src/projects.ts';
import {recordsRequest,STORAGE_KEY,SEED_KEY} from '../src/records.ts';
const data=new Map<string,string>([[SEED_KEY,'1']]);
Object.defineProperty(globalThis,'localStorage',{value:{getItem:(k:string)=>data.get(k)??null,setItem:(k:string,v:string)=>data.set(k,v)}});
const request=(items:unknown)=>recordsRequest('/api/records',{method:'POST',body:JSON.stringify({items})});
const companies=['a','b','c','d'].map(id=>({id,kind:'customer',name:'회사'+id,contacts:[{id:id+'p',contact:'담당'+id}]}));
const deal={id:'deal',kind:'deal',name:'브랜드 캠페인',customer:'a',advertiserContactId:'ap',agency:'b',agencyContactId:'bp',rep:'c',repContactId:'cp',stage:'협의 중',result:'미정',next:'수정 견적 전달',due:'2026-10-30'};
assert.equal((await request([...companies,deal])).status,200);
assert.deepEqual(projectCompanyIds(deal),['a','b','c']);
const agencyLog={id:'agency-log',kind:'log',customer:'b',contactId:'bp',deal:'deal',note:'견적 협의',date:'2026-10-25'};
assert.equal((await request([agencyLog,{...agencyLog,id:'rep-log',customer:'c',contactId:'cp'}])).status,200);
assert.equal((await request([{...agencyLog,id:'outside-log',customer:'d',contactId:'dp'}])).status,400);
assert.equal((await request([{...deal,agencyContactId:'cp'}])).status,400);
assert.equal((await request([{...deal,agency:'d',agencyContactId:'dp'}])).status,400);
assert.equal((await recordsRequest('/api/records?id=b',{method:'DELETE'})).status,400);
assert.equal((await recordsRequest('/api/records?id=deal',{method:'DELETE'})).status,400);
assert.equal((await request([{...companies[2],contacts:[{id:'other',contact:'기타'}]}])).status,400);
assert.equal((await request([{...deal,quotedAmount:'-1'}])).status,400);
assert.equal((await request([{...deal,start:'2026-11-02',end:'2026-11-01'}])).status,400);
assert.equal(projectStage({...deal,stage:'수주'}),'수주');
assert.equal(projectResult({...deal,result:undefined,stage:'실주'}),'실패');
const all=[...companies,deal,{...deal,id:'closed',stage:'완료',result:'수주'},{...deal,id:'lost',stage:'결과 확정',result:'미수주'}];
assert.equal(filterProjects(all).length,1);
assert.equal(filterProjects(all,'회사b','전체').length,3);
assert.equal(filterProjects(all,'수정 견적','완료')[0].id,'closed');
const saved=JSON.parse(data.get(STORAGE_KEY)!);
assert.equal(saved.filter((r:any)=>r.kind==='log').length,2);
assert.equal(saved.find((r:any)=>r.id==='agency-log').contactId,'bp');
console.log('PASS: project roles and contacts, agency/rep logs, linked-reference protection, amounts/dates, legacy mapping and filters');
const partnerProject={id:'partner-only',kind:'deal',name:'신규 캠페인',agency:'b',rep:'c',advertiserName:'새 브랜드',stage:'제안 준비',note:'미팅에서 캠페인 정보를 확인'};
assert.equal((await request([partnerProject])).status,200);
assert.equal((await request([{...agencyLog,id:'partner-meeting',deal:partnerProject.id}])).status,200);
const partnerRows=JSON.parse(data.get(STORAGE_KEY)!);
assert.equal(filterProjects(partnerRows,'새 브랜드','전체')[0].id,partnerProject.id);
assert.equal((await request([{id:'no-parties',kind:'deal',name:'미확인'}])).status,400);
assert.equal((await request([{id:'direct',kind:'deal',name:'직접 영업',advertiserName:'직접 브랜드',stage:'제안 준비'}])).status,200);
assert.equal(projectStage({...deal,stage:'제안 준비'}),'제안 준비');
assert.equal(projectStage({...deal,stage:'제안 완료'}),'제안 완료');
assert.equal(projectStage({...deal,stage:'협의 중'}),'협의 중');
console.log('PASS: partner-led projects without advertiser DB, partner logs, free-text brand search, direct sales and unchanged stages');

assert.equal(projectResult({...deal,result:'미정'}),'');
assert.equal(projectResult({...deal,result:'수주'}),'성공');
assert.equal(projectResult({...deal,result:'미수주'}),'실패');
assert.equal(projectResult({...deal,result:'보류'}),'');
assert.equal(projectResult({...deal,result:'성공'}),'성공');
assert.equal(projectResult({...deal,result:'실패'}),'실패');
assert.equal(filterProjects(all,'','미수주')[0].id,'lost');
assert.equal((await request([{...partnerProject,result:'성공',stage:'결과 확정'}])).status,200);
assert.equal(JSON.parse(data.get(STORAGE_KEY)!).find((r:any)=>r.id===partnerProject.id).result,'성공');
assert.equal((await request([{...partnerProject,result:'실패',stage:'결과 확정'}])).status,200);
assert.equal(JSON.parse(data.get(STORAGE_KEY)!).find((r:any)=>r.id===partnerProject.id).result,'실패');
console.log('PASS: unconfirmed result hidden, success/failure persistence, legacy outcomes and result filtering');

assert.equal(projectStage({...deal,stage:'결과 확정',result:'성공'}),'수주');
assert.equal(projectStage({...deal,stage:'결과 확정',result:'실패'}),'미수주');
assert.equal(projectStage({...deal,stage:'결과 확정',result:'미정'}),'협의 중');
assert.equal(projectStage({...deal,stage:'미수주',result:'성공'}),'미수주');
assert.equal(projectStage({...deal,stage:'협의 중',result:'실패'}),'협의 중');
assert.equal((await request([{...partnerProject,stage:'수주',result:''}])).status,200);
assert.equal(JSON.parse(data.get(STORAGE_KEY)!).find((r:any)=>r.id===partnerProject.id).stage,'수주');
assert.equal((await request([{...partnerProject,stage:'미수주',result:''}])).status,200);
assert.equal(JSON.parse(data.get(STORAGE_KEY)!).find((r:any)=>r.id===partnerProject.id).stage,'미수주');
console.log('PASS: single-stage outcomes, legacy success/failure mapping, won/lost persistence and filters');
const searchable=[{id:'search-company',kind:'customer',name:'검색회사',contacts:[{id:'assigned',contact:'새 담당자',department:'미디어팀'},{id:'unassigned',contact:'관련없는 담당자'}]},{id:'search-project',kind:'deal',name:'검색 캠페인',agency:'search-company',agencyContactId:'assigned',stage:'제안 준비'}];
assert.equal(filterProjects(searchable,'새 담당자')[0].id,'search-project');
assert.equal(filterProjects(searchable,'미디어팀')[0].id,'search-project');
assert.equal(filterProjects(searchable,'관련없는 담당자').length,0);
console.log('PASS: project search follows the current assigned contact and department');
