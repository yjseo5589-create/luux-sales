import assert from 'node:assert/strict';
import {readFile,readdir,mkdtemp,writeFile,rm,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createRequire} from 'node:module';
import {protectHtml,bundleHtml} from '../scripts/protect-pages.mjs';
import {loadSiteKey} from '../scripts/site-key.mjs';
const require=createRequire(import.meta.url),engine=require('staticrypt/lib/cryptoEngine.js'),codec=require('staticrypt/lib/codec.js').init(engine);
const salt=engine.generateRandomSalt(),password='test-only-credential-86721',hashedPassword=await engine.hashPassword(password,salt);
const plain='<!doctype html><html><body>PRIVATE_CONTENT<script type="module">console.log("private-app")</script></body></html>';
const protectedHtml=await protectHtml(plain,{salt,hashedPassword},'data:image/png;base64,AA==');
assert.ok(!protectedHtml.includes('PRIVATE_CONTENT'));
assert.ok(!protectedHtml.includes('private-app'));
assert.ok(!protectedHtml.includes(password));
assert.ok(!protectedHtml.includes(hashedPassword));
const config=JSON.parse(protectedHtml.match(/const protectedConfig=(\{.*\});/)[1]);
assert.equal(config.isRememberEnabled,false);
assert.equal((await codec.decode(config.staticryptEncryptedMsgUniqueVariableName,hashedPassword,salt)).decoded,plain);
const wrong=await engine.hashPassword('wrong-password',salt);
assert.equal((await codec.decode(config.staticryptEncryptedMsgUniqueVariableName,wrong,salt)).success,false);
const msg=config.staticryptEncryptedMsgUniqueVariableName;
const tampered=(msg[0]==='0'?'1':'0')+msg.slice(1);
assert.equal((await codec.decode(tampered,hashedPassword,salt)).success,false);
const temp=await mkdtemp(join(tmpdir(),'luux-security-test-'));
try{
 await assert.rejects(loadSiteKey(join(temp,'missing-key.json')),/missing/);
 await writeFile(join(temp,'bad-key.json'),'{}');
 await assert.rejects(loadSiteKey(join(temp,'bad-key.json')),/Invalid/);
 await mkdir(join(temp,'assets'));
 await writeFile(join(temp,'index.html'),'<html><head><script type="module" src="/luux-sales/assets/app.js"></script><link rel="stylesheet" href="/luux-sales/assets/app.css"></head></html>');
 await writeFile(join(temp,'assets/app.js'),'const logo="/luux-sales/landing-luux-logo.png";console.log("fixture-app");');
 await writeFile(join(temp,'assets/app.css'),'body{color:black}');
 await writeFile(join(temp,'landing-luux-logo.png'),'fixture-logo');
 const bundled=await bundleHtml(temp);
 assert.ok(bundled.html.includes('fixture-app'));
 assert.ok(bundled.html.includes('<style>body{color:black}</style>'));
 assert.ok(bundled.html.includes('data:image/png;base64,'));
 assert.ok(!bundled.html.includes('src="/luux-sales/assets/'));
 await writeFile(join(temp,'assets/lazy-chunk.js'),'private extra chunk');
 await assert.rejects(bundleHtml(temp),/Unbundled build chunks/);
}finally{await rm(temp,{recursive:true,force:true})}
// Production artifact must have no public executable app assets or resource IDs.
assert.deepEqual((await readdir('docs')).sort(),['.nojekyll','index.html']);
const artifact=await readFile('docs/index.html','utf8');
assert.ok(artifact.includes('staticryptEncryptedMsgUniqueVariableName'));
assert.ok(!artifact.includes('18XkBgWpN9n0Vyr6vyWqHBCptzo0YWotk'));
assert.ok(!artifact.includes('/assets/index-'));
assert.ok(!artifact.includes('dsshin@bushad.com'));
